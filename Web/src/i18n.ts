/// Returns the Strings table for `lang`, falling back to English when
/// the locale isn't translated yet. Use this everywhere instead of
/// `STRINGS[lang]` directly so untranslated locales never read
/// `undefined` from a Strings field.
export function pickStrings(lang: Lang): Strings {
  return STRINGS[lang] ?? en;
}

